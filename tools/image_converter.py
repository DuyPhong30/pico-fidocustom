#!/usr/bin/env python3
"""
image_converter.py - Tool to convert images/GIFs to C header for LILYGO T-Embed
Usage:
    python image_converter.py idle.png waiting.png confirmed.png timeout.png
Or:
    python image_converter.py --split 4cards.png
"""

import sys
import os
from PIL import Image

TARGET_W = 170
TARGET_H = 320

def rgb_to_rgb565(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    return (r5 << 11) | (g6 << 5) | b5

def image_to_rle(img_path):
    img = Image.open(img_path).convert("RGB")
    img = img.resize((TARGET_W, TARGET_H), Image.Resampling.LANCZOS)
    
    pixels = []
    for y in range(TARGET_H):
        for x in range(TARGET_W):
            r, g, b = img.getpixel((x, y))
            c = rgb_to_rgb565(r, g, b)
            pixels.append((c >> 8) & 0xFF)
            pixels.append(c & 0xFF)
            
    # RLE compression
    rle = []
    i = 0
    while i < len(pixels):
        hi = pixels[i]
        lo = pixels[i + 1]
        run = 1
        j = i + 2
        while j < len(pixels) and run < 255:
            if pixels[j] == hi and pixels[j + 1] == lo:
                run += 1
                j += 2
            else:
                break
        rle.extend([run, hi, lo])
        i = j
    return rle

def main():
    if len(sys.argv) < 5:
        print("Usage: python image_converter.py <idle.png> <waiting.png> <confirmed.png> <timeout.png>")
        return

    files = [
        ("img_idle", sys.argv[1]),
        ("img_waiting", sys.argv[2]),
        ("img_confirmed", sys.argv[3]),
        ("img_timeout", sys.argv[4])
    ]

    out_file = "tembed_images.h"
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by image_converter.py */\n")
        f.write("#ifndef _TEMBED_IMAGES_H_\n#define _TEMBED_IMAGES_H_\n\n")
        f.write("#include <stdint.h>\n#include <stddef.h>\n\n")
        f.write("#define TEMBED_IMG_W 170\n#define TEMBED_IMG_H 320\n\n")

        for name, path in files:
            print(f"Processing {name} from {path}...")
            rle = image_to_rle(path)
            f.write(f"static const uint8_t {name}_rle[{len(rle)}] = {{\n")
            for k in range(0, len(rle), 16):
                chunk = rle[k:k+16]
                line = "    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n"
                f.write(line)
            f.write(f"}};\n#define {name}_len {len(rle)}\n\n")

        f.write("#endif // _TEMBED_IMAGES_H_\n")
    print(f"Successfully generated {out_file}!")

if __name__ == "__main__":
    main()
