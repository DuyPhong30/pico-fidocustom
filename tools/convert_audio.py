#!/usr/bin/env python3
"""
tools/convert_audio.py
Converts MP3 audio clips to 16kHz 8-bit unsigned PCM C header (tembed_audio_data.h)
for LILYGO T-Embed MAX98357A I2S amplifier.
"""
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOUNDS_DIR = os.path.join(ROOT, "sounds")
OUTPUT_HEADER = os.path.join(ROOT, "tembed_audio_data.h")

def get_ffmpeg_cmd():
    local_ffmpeg = os.path.join(ROOT, "ffmpeg.exe")
    if os.path.exists(local_ffmpeg):
        return local_ffmpeg
    return "ffmpeg"

def convert_clip(input_mp3, start_sec=None, duration_sec=None):
    raw_out = input_mp3 + ".raw"
    ffmpeg_bin = get_ffmpeg_cmd()
    cmd = [ffmpeg_bin, "-y"]
    if start_sec is not None:
        cmd.extend(["-ss", str(start_sec)])
    cmd.extend(["-i", input_mp3, "-ar", "16000", "-ac", "1", "-f", "u8"])
    if duration_sec is not None:
        cmd.extend(["-t", str(duration_sec)])
    cmd.append(raw_out)

    print("Running:", " ".join(cmd))
    subprocess.check_call(cmd)
    with open(raw_out, "rb") as f:
        data = f.read()
    if os.path.exists(raw_out):
        os.remove(raw_out)
    return data

def main():
    print("Converting Kamen Rider audio files to tembed_audio_data.h...")
    boot_mp3 = os.path.join(SOUNDS_DIR, "boot.mp3")
    waiting_mp3 = os.path.join(SOUNDS_DIR, "waiting.mp3")
    confirmed_mp3 = os.path.join(SOUNDS_DIR, "confirmed.mp3")
    timeout_mp3 = os.path.join(SOUNDS_DIR, "timeout.mp3")

    # 1. Boot: Kamen Rider W (Double) transformation music ("nhạc mở máy")
    # From W Henshin MP3: start at 5.48s (after memories insertion, right into "Cyclone! Joker!" + Henshin fanfare)
    raw_boot = convert_clip(boot_mp3, start_sec=5.48, duration_sec=4.5)

    # 2. Waiting: Long continuous Faiz "Standing By" and electronic standby rhythm (~8.3s)
    raw_waiting = convert_clip(waiting_mp3)

    # 3. Confirmed: Faiz clear "COMPLETE!" voice announcement + photon stream burst
    # From Faiz Henshin MP3: start at 7.75s (exact beginning of "COMPLETE!" announcement)
    raw_confirmed = convert_clip(confirmed_mp3, start_sec=7.75, duration_sec=2.8)

    # 4. Timeout: Buzzer Error (~1.5s)
    raw_timeout = convert_clip(timeout_mp3, duration_sec=1.5)

    with open(OUTPUT_HEADER, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by tools/convert_audio.py */\n")
        f.write("#ifndef _TEMBED_AUDIO_DATA_H_\n#define _TEMBED_AUDIO_DATA_H_\n\n")
        f.write("#include <stdint.h>\n#include <stddef.h>\n\n")

        for name, data in [
            ("sound_boot", raw_boot),
            ("sound_waiting", raw_waiting),
            ("sound_confirmed", raw_confirmed),
            ("sound_timeout", raw_timeout)
        ]:
            f.write(f"static const uint8_t {name}_pcm[{len(data)}] = {{\n")
            for i in range(0, len(data), 16):
                chunk = data[i:i+16]
                line = "    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n"
                f.write(line)
            f.write(f"}};\n#define {name}_samples {len(data)}\n\n")

        f.write("#endif // _TEMBED_AUDIO_DATA_H_\n")
    print(f"Successfully generated {OUTPUT_HEADER} with {len(raw_boot)} boot bytes, {len(raw_waiting)} waiting bytes, {len(raw_confirmed)} confirmed bytes, {len(raw_timeout)} timeout bytes.")

if __name__ == "__main__":
    main()
